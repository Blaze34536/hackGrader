def _trim_source(code: str, limit: int = SYNTHETIC_FILE_CHARS) -> str:
    """Trim generated source on a line boundary when it exceeds its budget."""
    if len(code) <= limit:
        return code
    kept, used = [], 0
    for line in code.splitlines():
        if used + len(line) + 1 > limit:
            break
        kept.append(line)
        used += len(line) + 1
    return "\n".join(kept) or code[:limit]


def _subjects(blocks: list[str]) -> list[str]:
    """Extract concise function-name topics for generated README examples."""
    names = [name for block in blocks for name in _FUNCTION_NAME.findall(block)]
    return [name.replace("_", " ").capitalize() for name in names[:6]]


def synthetic_readme(label: int, blocks: list[str], slug: str, rng: random.Random) -> str:
    """Create intentionally machine- or human-labeled synthetic README content."""
    subjects = _subjects(blocks) or ["the entry point"]
    title = slug.replace("-", " ").title()
    if label:
        bullets = "\n".join(f"- {subject}" for subject in subjects)
        modules = "\n".join(f"- `src/module_{position}.py` - covers {subject.lower()}" for position, subject in enumerate(subjects))
        setup, verify = rng.choice(AI_SECTIONS)
        return (
            f"# {title}\n\nA hackathon project that keeps every module small, consistent and easy to read.\n\n"
            f"## Overview\n\n{rng.choice(AI_OVERVIEWS)}\n\n## Features\n\n{bullets}\n\n## {setup}\n\n"
            "1. Install the dependencies listed in the project.\n2. Run the entry point.\n3. Review the output it prints.\n\n"
            f"## Project Structure\n\n{modules}\n\n## {verify}\n\n{rng.choice(AI_CLOSERS)}\n\n"
            "## License\n\nReleased for the hackathon submission under the MIT License.\n"
        )
    return (
        f"# {title}\n\nquick hack we threw together over the weekend. {rng.choice(HUMAN_OPENERS)}\n\n"
        "## what it does\n\n- takes the input and spits the answer back out\n- !! the parser is gonna break on weird input\n\n"
        "## notes\n\n- I need to fix the " + subjects[0].lower() + " later (TODO)\n"
        "- a lot of stuff is still hardcoded for the demo\n- teh setup steps are around here somewhere\n"
        "- my todo list lives in the issues\n"
    )


def repo_dump(label: int, blocks: list[str], slug: str, *, with_readme: bool, lead: str = "") -> str:
    """Render source snippets and optional README into a repository dump."""
    names = [f"src/module_{position}.py" for position in range(len(blocks))]
    readme = synthetic_readme(label, blocks, slug, random.Random(zlib.crc32(slug.encode("utf-8")))) if with_readme else ""
    if readme:
        names.append("README.md")
    header = f"REPOSITORY: hackathon/{slug}\nDEFAULT BRANCH: main\nFILES INCLUDED ({len(names)}): {', '.join(names)}"
    budget = MODEL_DUMP_CHARS - len(header) - 200 - (len(readme) + 30 if readme else 0)
    per_file = min(SYNTHETIC_FILE_CHARS, max(160, budget // len(blocks)))
    body = ""
    for position, (name, code) in enumerate(zip(names[:len(blocks)], blocks, strict=True)):
        source = _trim_source(code, per_file)
        if position == 0 and lead:
            source = f"{lead}\n{source}"
        body += f"\n\n--- FILE: {name} ---\n{source}"
    if readme:
        body += f"\n\n--- FILE: README.md ---\n{readme}"
    return report.trim_dump(header + body)


def _sample_components(samples: list[AIGSample]) -> list[list[AIGSample]]:
    """Group samples connected by content or CodeNet problem lineage."""
    parents = list(range(len(samples)))
    identity_owner: dict[str, int] = {}

    def root(index: int) -> int:
        """Find and compress the representative of a sample's lineage component."""
        while parents[index] != index:
            parents[index] = parents[parents[index]]
            index = parents[index]
        return index

    for index, sample in enumerate(samples):
        for identity in sample_source_groups(sample):
            previous = identity_owner.setdefault(identity, index)
            first_root = root(index)
            second_root = root(previous)
            if first_root != second_root:
                parents[second_root] = first_root

    components: dict[int, list[AIGSample]] = {}
    for index, sample in enumerate(samples):
        components.setdefault(root(index), []).append(sample)
    return list(components.values())


def synthetic_repo_rows(samples: list[AIGSample], count: int = SYNTHETIC_REPOS) -> list[dict[str, Any]]:
    """Build synthetic projects without linking otherwise independent problems."""
    if count <= 0 or SYNTHETIC_FILES < 2:
        return []

    components = _sample_components(samples)
    files_per_project = SYNTHETIC_FILES
    rows = []
    for label in (1, 0):
        generated = 0
        for component in components:
            component_samples = [sample for sample in component if sample.label == label]
            for start in range(0, len(component_samples), files_per_project):
                if generated >= count:
                    break
                chosen = component_samples[start:start + files_per_project]
                if len(chosen) < 2:
                    continue
                lineage = "|".join(
                    group for sample in chosen for group in sample_source_groups(sample)
                )
                project_id = hashlib.sha256(lineage.encode("utf-8")).hexdigest()[:16]
                slug = f"synthetic-project-{project_id}"
                url = f"https://github.com/hackathon/{slug}"
                rows.append(core(
                    repo_dump(
                        label,
                        [sample.code for sample in chosen],
                        slug,
                        with_readme=bool(label) or not generated % 2,
                    ),
                    url, seed=zlib.crc32(url.encode("utf-8")), label=label, kind="repository",
                    source_type="synthetic_repository",
                    source_groups=[
                        url,
                        *(group for sample in chosen for group in sample_source_groups(sample)),
                    ],
                ))
                generated += 1
    return rows


def artifact_rows(samples: list[AIGSample], count: int = ARTIFACT_ROWS) -> list[dict[str, Any]]:
    """Add explicit AI-marker examples without reusing their underlying sources."""
    ai_samples = [sample for sample in samples if sample.label == 1]
    if not ai_samples:
        return []
    rows = []
    for index, sample in enumerate(ai_samples[:max(0, count)]):
        lead = ARTIFACT_LINES[index % len(ARTIFACT_LINES)]
        source_groups = sample_source_groups(sample)
        artifact_id = hashlib.sha256(
            f"{lead}|{'|'.join(source_groups)}".encode()
        ).hexdigest()[:16]
        slug = f"project-{artifact_id}"
        url = f"https://github.com/code-review-samples/{slug}"
        if index % 2:
            prompt = repo_dump(
                1, [sample.code], slug, with_readme=True, lead=lead
            )
            kind = "repository"
        else:
            prompt = f"{lead}\n--- FILE: snippet.py ---\n{sample.code}"
            kind = "snippet"
        analysis = detector.analyze(prompt)
        if has_explicit_artifact(analysis):
            rows.append(core(
                prompt, url, seed=zlib.crc32(f"{lead}{index}".encode()), analysis=analysis,
                label=1, kind=kind, source_type="artifact",
                source_groups=source_groups,
            ))
    return rows
