class TestPageGeometry(unittest.TestCase):
    """Check the drawn page itself: real pages, numbering, and no highlight boxes."""

    def test_every_project_opens_its_own_page_after_the_cover(self) -> None:
        """Give the cover and each project a page of its own."""
        projects, cover = _two_projects_for_geometry()
        with TemporaryDirectory() as directory:
            path = Path(directory) / "report.pdf"
            errors = write_pdf(path, projects, cover)

            self.assertEqual(errors, 0)
            self.assertEqual(count_pages(path), 3)

    def test_page_numbers_and_running_headers_are_stamped(self) -> None:
        """Stamp the page count on every page and the project name on its page."""
        projects, cover = _two_projects_for_geometry()
        pages, _, _ = _render(projects, cover)

        self.assertEqual(len(pages), 3)
        self.assertIn("Page 1 of 3", pages[0])
        self.assertIn("Page 3 of 3", pages[2])
        # The report title is drawn on the cover and again in each project page's header.
        self.assertIn("Hackathon Code Review Report", pages[0])
        self.assertIn("Hackathon Code Review Report", pages[2])
        self.assertIn("student/project", pages[1])
        self.assertIn("student/other", pages[2])

    def test_no_page_draws_a_filled_rectangle(self) -> None:
        """Draw no tinted or solid box for a failed or a scored project."""
        for project in (FAILED, SCORED):
            with self.subTest(project=str(project.get("status"))):
                _, streams, errors = _render([_context(project)])
                text = "\n".join(_page_texts(streams))

                self.assertEqual(errors, 0)
                # Refuse a vacuous pass: the streams must decode to the drawn page.
                self.assertTrue(streams)
                self.assertIn("Code quality reported", text)
                filled = [
                    match.group(0)
                    for stream in streams
                    for match in FILLED_RECTANGLE.finditer(stream)
                ]
                self.assertEqual(filled, [])


class TestJudgeOnlyRendering(unittest.TestCase):
    """Render stored report scores without applying stale automatic annotations."""

    REPORT = (
        "1. AI Involvement Score (0-100%): 74%\n"
        "Ranked AI evidence (strongest to weakest):\n"
        "Rank 1: `# generated by ChatGPT` in app.py - explicit AI attribution.\n\n"
        "2. Code Quality Score (0-100%): 68%\n"
        "- Deductions: -12% no README with setup instructions\n\n"
        "3. Summary & Notable Findings: A stylesheet and a quiz page with eleven screens.\n"
    )
    PROJECT = "https://github.com/student/stale"

    @classmethod
    def _stale(cls) -> dict:
        """Build one row the way the build that preceded judge-owned scores wrote it.

        The stored annotation is deliberately stale: scores disagree with the report and legacy
        flags and measurement fields remain present, so the renderer must ignore them.
        """
        return {
            cls.PROJECT: {
                "status": 200,
                "content": cls.REPORT,
                "analysis": {
                    "ai_score": 2,
                    # This prompt-context measurement must not be substituted for judge output.
                    "quality_score": 90,
                    "ai_evidence": ["generated-code marker quoted"],
                    "quality_deductions": ["-6% a single function runs for 95 lines"],
                    "coverage": {
                        "files_shown": 6,
                        "files_found": 6,
                        "files_fetched": 6,
                    },
                    "metrics": {"chars": 9000},
                },
                "ai_score": 2,
                "code_score": 90,
                "detector_ai_score": 2,
                "flags": ["HIGH_AI_USAGE", "MODEL_DISAGREES"],
                "report_findings": ["old stale finding"],
                "evidence": ["generated-code marker quoted"],
                "deductions": ["-6% a single function runs for 95 lines"],
                "coverage": {"files_shown": 6, "files_found": 6, "files_fetched": 6},
                "summary": "",
            }
        }

    @staticmethod
    def _write(directory: str, scores: dict) -> Path:
        """Save a scores file where the command will read it."""
        path = Path(directory) / "scores.json"
        path.write_text(json.dumps(scores), encoding="utf-8")
        return path

    def test_annotation_uses_the_judge_report_and_discards_old_flags(self) -> None:
        """Parse judge scores and evidence, ignoring stale flags and measurements."""
        annotated = Reporting().annotate_all(self._stale())
        row = annotated[self.PROJECT]

        self.assertEqual(row["ai_score"], 74)
        self.assertEqual(row["code_score"], 68)
        self.assertEqual(
            row["evidence"],
            ["`# generated by ChatGPT` in app.py - explicit AI attribution."],
        )
        self.assertNotIn("flags", row)
        self.assertNotIn("detector_ai_score", row)

    def test_rendering_uses_the_judge_report_and_ignores_stored_flags(self) -> None:
        """Draw stored scores while excluding legacy flags and findings from the page."""
        with TemporaryDirectory() as directory:
            path = self._write(directory, self._stale())
            out = Path(directory) / "report.pdf"
            before = path.read_bytes()

            self.assertEqual(cli.main([str(path), str(out)]), 0)

            text = "\n".join(_page_texts(_pages(out)))
            self.assertIn("74%", text)
            self.assertIn("68%", text)
            self.assertNotIn("\n2%\n", text)
            self.assertNotIn("\n90%\n", text)
            self.assertNotIn("HIGH AI USAGE", text)
            self.assertNotIn("old stale finding", text)
            self.assertEqual(path.read_bytes(), before)

    def test_pdf_command_no_longer_accepts_the_removed_refresh_option(self) -> None:
        """Reject the obsolete flag rather than suggesting re-annotation remains supported."""
        with TemporaryDirectory() as directory:
            path = self._write(directory, self._stale())
            out = Path(directory) / "report.pdf"

            with self.assertRaises(SystemExit) as raised:
                cli.main([str(path), str(out), "--no-refresh"])

            self.assertEqual(raised.exception.code, 2)

    def test_a_row_that_cannot_be_parsed_keeps_null_scores_without_flags(self) -> None:
        """Keep invalid report scores empty and preserve its status without flags."""
        scores = self._stale()
        scores[self.PROJECT]["content"] = "no report here"
        annotated = Reporting().annotate_all(scores)

        self.assertIsNone(annotated[self.PROJECT]["ai_score"])
        self.assertIsNone(annotated[self.PROJECT]["code_score"])
        self.assertEqual(annotated[self.PROJECT]["status"], 200)

        self.assertNotIn("flags", annotated[self.PROJECT])


class TestSavedScoresFile(unittest.TestCase):
    """Write the annotated, sorted file the gallery pipeline leaves behind."""

    CLEAN = "https://github.com/student/clean"
    # A second report ensures saved output is ordered by its judge-provided scores.
    CLEAN_REPORT = (
        "1. AI Involvement Score (0-100%): 20%\n"
        "Ranked AI evidence (strongest to weakest):\n"
        "Rank 1: `TODO` in app.py with no generated marker, a weak signal.\n\n"
        "2. Code Quality Score (0-100%): 88%\n"
        "- Deductions: no deductions applied\n\n"
        "3. Summary & Notable Findings: A short script that prints one value from app.py.\n"
    )

    @staticmethod
    def _write(directory: str, scores: dict) -> Path:
        """Save a scores file where the pipeline will read and rewrite it."""
        path = Path(directory) / "scores.json"
        path.write_text(json.dumps(scores), encoding="utf-8")
        return path

    def test_generate_report_saves_the_shared_pass_sorted_by_score(self) -> None:
        """Persist the shared judge annotation in ascending score order, with no flags."""
        stale = TestJudgeOnlyRendering._stale()
        # Deliberately no stored ai_score, code_score, or evidence: every reported field is
        # derived from the report text on annotation, never read back from the file.
        stale[self.CLEAN] = {
            "status": 200,
            "content": self.CLEAN_REPORT,
            "analysis": {
                "ai_score": 20,
                "quality_score": 85,
                "coverage": {"files_shown": 4},
                "metrics": {"chars": 4000},
            },
        }
        with TemporaryDirectory() as directory:
            path = self._write(directory, stale)
            Reporting(json_path=str(path)).generate_report()
            written = json.loads(path.read_text(encoding="utf-8"))

        self.assertEqual(
            list(written), [self.CLEAN, TestJudgeOnlyRendering.PROJECT]
        )
        self.assertEqual(written[TestJudgeOnlyRendering.PROJECT]["ai_score"], 74)
        self.assertEqual(written[TestJudgeOnlyRendering.PROJECT]["code_score"], 68)
        self.assertNotIn("detector_code_score", written[TestJudgeOnlyRendering.PROJECT])
        self.assertEqual(written[self.CLEAN]["ai_score"], 20)
        self.assertEqual(written[self.CLEAN]["code_score"], 88)
        self.assertNotIn("flags", written[self.CLEAN])
        self.assertNotIn("flags", written[TestJudgeOnlyRendering.PROJECT])

    def test_generate_report_refuses_a_missing_or_unreadable_file(self) -> None:
        """Fail loudly rather than writing an annotation over an unusable input."""
        with TemporaryDirectory() as directory:
            with self.assertRaises(FileNotFoundError):
                Reporting(json_path=str(Path(directory) / "absent.json")).generate_report()

            broken = self._write(directory, {})
            broken.write_text("{not json", encoding="utf-8")
            with self.assertRaises(ValueError):
                Reporting(json_path=str(broken)).generate_report()


def _two_projects_for_geometry() -> tuple[list[dict], dict]:
    """Prepare two project contexts and their cover for page-level checks."""
    projects = build_context({PROJECT: SCORED, SECOND: OTHER})
    return projects, _cover(projects)


def _panel_styles(story: list) -> dict[str, str]:
    """Map each panel title's text to the style name it was drawn with."""
    return {
        flowable.getPlainText(): flowable.style.name
        for flowable in story
        if isinstance(flowable, Paragraph) and flowable.style.name.startswith("PanelTitle")
    }


