def _context(project: dict) -> dict:
    """Prepare one project's stored scores the way the command hands them over."""
    return build_context({PROJECT: project})[0]


def _render(projects: list[dict], cover: dict | None = None) -> tuple[list[str], list[str], int]:
    """Render projects to a temporary PDF and return its per-page text and streams."""
    with TemporaryDirectory() as directory:
        path = Path(directory) / "report.pdf"
        errors = write_pdf(path, projects, cover)
        streams = _pages(path)
        return _page_texts(streams), streams, errors


def _pages(path: Path) -> list[str]:
    """Decode the ASCII85 and Flate page streams reportlab writes into the PDF."""
    pages = []
    for match in STREAM.finditer(path.read_bytes()):
        data = match.group(1).strip()
        try:
            pages.append(zlib.decompress(base64.a85decode(data, adobe=True)).decode("latin-1"))
        except (ValueError, zlib.error):
            try:
                pages.append(zlib.decompress(data).decode("latin-1"))
            except zlib.error:
                continue
    return pages


def _unescape(value: str) -> str:
    """Undo the PDF string escapes reportlab applies to drawn text."""
    result: list[str] = []
    index = 0
    while index < len(value):
        char = value[index]
        if char != "\\" or index + 1 >= len(value):
            result.append(char)
            index += 1
            continue
        following = value[index + 1]
        if following.isdigit():
            octal = value[index + 1 : index + 4]
            result.append(chr(int(octal, 8)))
            index += 1 + len(octal)
            continue
        result.append({"n": "\n", "r": "\r", "t": "\t"}.get(following, following))
        index += 2
    return "".join(result)


def _drawn_text(stream: str) -> str:
    """Collect the text one decoded page stream draws."""
    return "\n".join(_unescape(match.group(0)[1 : match.group(0).rindex(")")]) for match in TEXT_OPERATOR.finditer(stream))


def _page_texts(streams: list[str]) -> list[str]:
    """Collect the text every decoded page draws, in page order."""
    return [_drawn_text(stream) for stream in streams]


def _cover(projects: list[dict], **overrides: object) -> dict:
    """Build a cover record with a fixed stamp and build tag."""
    options: dict = {"generated_at": GENERATED_AT, "model_tag": MODEL_TAG}
    options.update(overrides)
    return cover_context("scores.json", projects, **options)


class TestScoreTable(unittest.TestCase):
    """Show the reported scores and nothing that restates them."""

    def test_only_the_reported_scores_are_printed(self) -> None:
        """Print the judge's reported scores and no measured or model-said column."""
        pages, _, errors = _render([_context(SCORED)])
