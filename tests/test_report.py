STREAM = re.compile(rb"stream\r?\n(.*?)endstream", re.DOTALL)
# reportlab writes each drawn text run as a PDF string followed by the Tj text operator.
TEXT_OPERATOR = re.compile(r"\((?:\\.|[^\\()])*\)\s*Tj")
# A filled rectangle is the only way a page can carry a tinted or solid box.
FILLED_RECTANGLE = re.compile(r"[-\d.]+ [-\d.]+ [-\d.]+ [-\d.]+ re\s+f\*?")

